const r    = require('express').Router();
const auth = require('../middleware/auth');
const w    = require('../utils/asyncHandler');
const c    = require('../controllers/quranController');
r.get('/qiraat',        auth, w(c.listQiraat));
r.post('/qiraat',       auth, w(c.createQiraa));
r.put('/qiraat/:id',    auth, w(c.updateQiraa));
r.delete('/qiraat/:id', auth, w(c.removeQiraa));
r.get('/riwayat',        auth, w(c.listRiwayat));
r.post('/riwayat',       auth, w(c.createRiwaya));
r.put('/riwayat/:id',    auth, w(c.updateRiwaya));
r.delete('/riwayat/:id', auth, w(c.removeRiwaya));
r.get('/turuq',        auth, w(c.listTuruq));
r.post('/turuq',       auth, w(c.createTariq));
r.put('/turuq/:id',    auth, w(c.updateTariq));
r.delete('/turuq/:id', auth, w(c.removeTariq));
r.get('/groups',          auth, w(c.listGroups));
r.post('/groups',         auth, w(c.createGroup));
r.post('/groups/known',   auth, w(c.addKnownGroups));
r.put('/groups/:id',      auth, w(c.updateGroup));
r.delete('/groups/:id',   auth, w(c.removeGroup));
module.exports = r;
