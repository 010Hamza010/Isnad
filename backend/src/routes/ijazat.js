const r    = require('express').Router();
const auth = require('../middleware/auth');
const w    = require('../utils/asyncHandler');
const c    = require('../controllers/ijazatController');
const express = require('express');
r.get('/settings',    auth, w(c.getSettings));
r.put('/settings',    auth, w(c.saveSettings));
r.delete('/settings', auth, w(c.resetSettings));
r.get('/',            auth, w(c.list));
r.get('/:id',         auth, w(c.get));
r.post('/',           auth, w(c.create));
r.delete('/:id',      auth, w(c.remove));
r.post('/:id/revoke',   auth, w(c.revoke));
r.post('/:id/freeze',   auth, w(c.freeze));
r.get('/:id/document',  auth, w(c.document));
r.post('/:id/pdf',      auth, express.raw({ type: 'application/pdf', limit: '20mb' }), w(c.uploadPdf));
r.get('/:id/pdf',       auth, w(c.pdf));
r.delete('/:id/revoke', auth, w(c.unrevoke));
module.exports = r;
